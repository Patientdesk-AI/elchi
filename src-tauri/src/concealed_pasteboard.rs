//! Transient macOS pasteboard writes that clipboard history apps should skip.
//!
//! Pasting through the clipboard puts the transcript on the general pasteboard
//! and then puts the user's previous content back. Neither is a copy the user
//! made, so both are declared alongside the nspasteboard.org marker types,
//! which well-behaved clipboard managers (Maccy, Raycast, Paste, ...) honor by
//! not recording the change. Writes the user asked to keep on the clipboard
//! must not go through here.

use objc2::rc::{autoreleasepool, Retained};
use objc2::AnyThread;
use objc2_app_kit::{
    NSBitmapFormat, NSBitmapImageRep, NSDeviceRGBColorSpace, NSPasteboard, NSPasteboardType,
    NSPasteboardTypeString, NSPasteboardTypeTIFF,
};
use objc2_foundation::{NSArray, NSCopying, NSData, NSInteger, NSString};

/// Concealment marker types from the nspasteboard.org convention. These are
/// conventions; nothing enforces them.
pub(crate) const CONCEALMENT_TYPES: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

/// Writes `text` to the general pasteboard, tagged as transient and concealed.
pub(crate) fn write_text(text: &str) -> Result<(), String> {
    write_text_to(&NSPasteboard::generalPasteboard(), text)
}

/// Writes an RGBA image to the general pasteboard as TIFF, tagged as transient
/// and concealed.
pub(crate) fn write_image(image: &tauri::image::Image<'_>) -> Result<(), String> {
    write_image_to(&NSPasteboard::generalPasteboard(), image)
}

fn write_text_to(pasteboard: &NSPasteboard, text: &str) -> Result<(), String> {
    // SAFETY: NSPasteboardTypeString is a read-only framework static.
    let data_type = unsafe { NSPasteboardTypeString };
    autoreleasepool(|_| {
        declare_with_markers(pasteboard, data_type)?;
        if pasteboard.setString_forType(&NSString::from_str(text), data_type) {
            Ok(())
        } else {
            Err("setString:forType: failed".to_string())
        }
    })
}

fn write_image_to(
    pasteboard: &NSPasteboard,
    image: &tauri::image::Image<'_>,
) -> Result<(), String> {
    let width = image.width() as usize;
    let height = image.height() as usize;
    let rgba = image.rgba();
    if width == 0 || height == 0 || rgba.len() != width * height * 4 {
        return Err("image is empty or not RGBA".to_string());
    }

    // SAFETY: NSPasteboardTypeTIFF is a read-only framework static.
    let data_type = unsafe { NSPasteboardTypeTIFF };
    autoreleasepool(|_| {
        let tiff = rgba_to_tiff(rgba, width, height)?;
        declare_with_markers(pasteboard, data_type)?;
        if pasteboard.setData_forType(Some(&tiff), data_type) {
            Ok(())
        } else {
            Err("setData:forType: failed".to_string())
        }
    })
}

/// Clears the pasteboard and declares `data_type` together with the marker
/// types in one change, so no observer can see the content without them.
fn declare_with_markers(
    pasteboard: &NSPasteboard,
    data_type: &NSPasteboardType,
) -> Result<(), String> {
    let mut types: Vec<Retained<NSString>> = Vec::with_capacity(1 + CONCEALMENT_TYPES.len());
    types.push(data_type.copy());
    for t in CONCEALMENT_TYPES {
        types.push(NSString::from_str(t));
    }
    let types = NSArray::from_retained_slice(&types);

    // declareTypes:owner: returns the new changeCount, or 0 on failure.
    let change_count: NSInteger = unsafe { pasteboard.declareTypes_owner(&types, None) };
    if change_count <= 0 {
        return Err("declareTypes:owner: failed".to_string());
    }
    // The markers carry no data; their presence is the signal.
    let empty = NSString::from_str("");
    for t in CONCEALMENT_TYPES {
        pasteboard.setString_forType(&empty, &NSString::from_str(t));
    }
    Ok(())
}

fn rgba_to_tiff(rgba: &[u8], width: usize, height: usize) -> Result<Retained<NSData>, String> {
    // A null plane pointer makes the rep allocate (and own) its own buffer.
    let rep = unsafe {
        NSBitmapImageRep::initWithBitmapDataPlanes_pixelsWide_pixelsHigh_bitsPerSample_samplesPerPixel_hasAlpha_isPlanar_colorSpaceName_bitmapFormat_bytesPerRow_bitsPerPixel(
            NSBitmapImageRep::alloc(),
            std::ptr::null_mut(),
            width as NSInteger,
            height as NSInteger,
            8,
            4,
            true,
            false,
            NSDeviceRGBColorSpace,
            NSBitmapFormat::AlphaNonpremultiplied,
            (width * 4) as NSInteger,
            32,
        )
    }
    .ok_or("NSBitmapImageRep init failed")?;

    let dst = rep.bitmapData();
    if dst.is_null() {
        return Err("NSBitmapImageRep has no bitmap data".to_string());
    }
    // SAFETY: the rep was created with exactly width * 4 bytes per row and no
    // padding, so its buffer holds rgba.len() bytes.
    unsafe { std::ptr::copy_nonoverlapping(rgba.as_ptr(), dst, rgba.len()) };

    rep.TIFFRepresentation()
        .ok_or_else(|| "TIFFRepresentation failed".to_string())
}

#[cfg(test)]
mod tests {
    use super::*;
    use objc2::msg_send;

    /// Held by each test: cargo runs tests on parallel threads, and two of them
    /// writing pasteboards at once sometimes lose a declared type (about 1 run
    /// in 25). The app itself writes the clipboard from one place at a time.
    static SERIAL: std::sync::Mutex<()> = std::sync::Mutex::new(());

    /// A private pasteboard, so tests never touch the user's real clipboard.
    struct PrivatePasteboard(Retained<NSPasteboard>);

    impl Drop for PrivatePasteboard {
        fn drop(&mut self) {
            let _: () = unsafe { msg_send![&*self.0, releaseGlobally] };
        }
    }

    fn declared_types(pasteboard: &NSPasteboard) -> Vec<String> {
        pasteboard
            .types()
            .map(|types| types.iter().map(|t| t.to_string()).collect())
            .unwrap_or_default()
    }

    #[test]
    fn text_write_declares_concealment_markers() {
        let _serial = SERIAL.lock().unwrap_or_else(|e| e.into_inner());
        let pb = PrivatePasteboard(NSPasteboard::pasteboardWithUniqueName());
        write_text_to(&pb.0, "dictated text").expect("concealed text write");

        let types = declared_types(&pb.0);
        for marker in CONCEALMENT_TYPES {
            assert!(types.iter().any(|t| t == marker), "missing {marker}");
        }
        let text = pb.0.stringForType(unsafe { NSPasteboardTypeString });
        assert_eq!(
            text.map(|s| s.to_string()).as_deref(),
            Some("dictated text")
        );
    }

    #[test]
    fn image_write_declares_concealment_markers() {
        let _serial = SERIAL.lock().unwrap_or_else(|e| e.into_inner());
        let pb = PrivatePasteboard(NSPasteboard::pasteboardWithUniqueName());
        let pixels = [255u8, 0, 0, 255, 0, 255, 0, 128];
        let image = tauri::image::Image::new(&pixels, 2, 1);
        write_image_to(&pb.0, &image).expect("concealed image write");

        let types = declared_types(&pb.0);
        for marker in CONCEALMENT_TYPES {
            assert!(types.iter().any(|t| t == marker), "missing {marker}");
        }
        let tiff = pb.0.dataForType(unsafe { NSPasteboardTypeTIFF });
        assert!(tiff.is_some_and(|data| data.length() > 0));
    }
}
